// Canonical event metadata and the types that cross the pipeline.
//
// Design doc 18 lists the fields every event must carry: event_id, tenant,
// risk_domain, order_id, event_type, domain_seq, journal_version, owner_epoch,
// payload_hash, accepted_state and the L0..L4 timestamps. This header is that
// list, made concrete.
//
// Two constraints shape the layout:
//
//   * InputEnvelope must be trivially copyable, because it travels in a ring
//     slot and doc 8 restricts slots to trivially copyable types that own no
//     external pointer. So there are no std::strings here: a symbol is an id, a
//     large payload is a PoolHandle, and anything variable-length lives in the
//     pool and not in the slot.
//   * A business identity is never a memory address and never a ring index
//     (LI-12, doc 19.3). order_id, exec_id and event_id are explicit values
//     that survive a restart and a replay.
//
// Money and quantity are fixed point. Doc 10 forbids -ffast-math and any
// "optimization" of the domain arithmetic, so quantities are scaled integers
// with checked addition, never doubles.
#pragma once

#include <cstdint>
#include <string_view>
#include <type_traits>

#include "llx/pool.hpp"

namespace llx {

// --- fixed point -----------------------------------------------------------

// Quantity in units of 1e-6, price in units of 1e-5. The scales are the ones a
// netting FX/CFD account needs for lot sizes and 5-digit quotes; they are
// configuration-visible so a differential run can prove the baseline and the
// optimized pipeline used the same ones.
constexpr std::int64_t kQtyScale = 1000000;
constexpr std::int64_t kPxScale = 100000;

using Qty = std::int64_t;
using Px = std::int64_t;
using OrderId = std::uint64_t;
using ExecId = std::uint64_t;
using DomainId = std::uint32_t;
using SymbolId = std::uint32_t;

// Checked addition. An overflow here is a contradiction in the fill ledger, not
// a value to wrap around, so it is reported and the order is quarantined
// (doc 4 "Business", LI-42).
constexpr bool checked_add(std::int64_t a, std::int64_t b, std::int64_t& out) noexcept {
    if (b > 0 && a > INT64_MAX - b) return false;
    if (b < 0 && a < INT64_MIN - b) return false;
    out = a + b;
    return true;
}

constexpr bool checked_sub(std::int64_t a, std::int64_t b, std::int64_t& out) noexcept {
    if (b < 0 && a > INT64_MAX + b) return false;
    if (b > 0 && a < INT64_MIN + b) return false;
    out = a - b;
    return true;
}

// --- identity --------------------------------------------------------------

// 128-bit business identity, doc 18. Generated by the producer of the event and
// stable across a resend, so a FIX PossDup replay dedups on identity rather
// than on arrival order (doc 19.3).
struct EventId {
    std::uint64_t hi = 0;
    std::uint64_t lo = 0;
    bool is_null() const noexcept { return hi == 0 && lo == 0; }
    friend bool operator==(const EventId& a, const EventId& b) noexcept {
        return a.hi == b.hi && a.lo == b.lo;
    }
    friend bool operator<(const EventId& a, const EventId& b) noexcept {
        return a.hi != b.hi ? a.hi < b.hi : a.lo < b.lo;
    }
};

// --- enumerations ----------------------------------------------------------

enum class Side : std::uint8_t { None = 0, Buy = 1, Sell = 2 };

enum class EventType : std::uint8_t {
    None = 0,
    NewOrder,        // inbound command, admission-controlled
    CancelRequest,   // inbound command, causally bound to a prior order
    ReplaceRequest,  // inbound command, quantity up/down and price change
    ExecutionReport, // inbound business proof from the LP, must not be dropped
    SessionControl,  // logon / heartbeat / resend: liveness, never starved
    CommitResult,    // internal: a P06 outcome arriving back at the owner
    Tick,            // internal: lets a test advance timers deterministically
};

// Lane classification of doc 12. The lane decides the full policy, which is the
// whole point of distinguishing them: an unaccepted New may be refused, an
// accepted execution receipt may not.
enum class Lane : std::uint8_t {
    SessionControl = 0,  // must remain serviced (LI-19)
    AcceptedReceipt = 1, // safety critical, no silent drop (LI-20)
    CancelReplace = 2,   // high priority but causally ordered (LI-36)
    NewOrder = 3,        // admission-controlled (LI-21)
    Telemetry = 4,       // sampled, droppable with a counter (LI-26)
};

constexpr Lane lane_of(EventType t) noexcept {
    switch (t) {
        case EventType::SessionControl: return Lane::SessionControl;
        case EventType::ExecutionReport: return Lane::AcceptedReceipt;
        case EventType::CancelRequest:
        case EventType::ReplaceRequest: return Lane::CancelReplace;
        default: return Lane::NewOrder;
    }
}

enum class ExecType : std::uint8_t {
    None = 0,
    New,           // order acknowledged working at the LP
    PartialFill,
    Fill,
    Canceled,
    Replaced,
    Rejected,
    Expired,
};

// Doc 18. The outcome of offering an event to the engine.
enum class AdmissionOutcome : std::uint8_t {
    AcceptedForProcessing,
    RejectedOverload,        // bounded refusal before durable admission (LI-21)
    HeldForReconciliation,   // outcome unknown; held, never retried (LI-18)
    RetryLaterNoAdmission,   // transient, caller may offer again
    InvalidInput,
    EngineHalted,
    DuplicateIgnored,        // same event_id already applied exactly once
    OutOfOrder,              // causal predecessor has not been applied
    StaleEpoch,              // fenced out by a newer owner (LI-14, LI-47)
};

// Doc 12 service states.
enum class ServiceMode : std::uint8_t {
    Warmup = 0,
    Normal = 1,
    Watch = 2,
    ShedNew = 3,
    ReconOnly = 4,
    Halted = 5,
};

// Doc 13. Note what Unknown means: the transaction may or may not have
// committed. LI-17 forbids treating it as a failure, because reissuing the
// business command would then risk a duplicate order at the LP.
enum class CommitOutcome : std::uint8_t {
    Committed,
    Rejected,   // the store refused; staged state is discarded
    Unknown,    // lost acknowledgement; resolve by idempotency key (CW-17)
};

// Doc 3 latency spans. They measure different things and doc 3 forbids adding
// or averaging across them, so each sample carries which span it belongs to.
enum class Span : std::uint8_t {
    L0_ReceiveToRoute = 0,
    L1_QueueWait = 1,
    L2_DecisionCompute = 2,
    L3_DurableAdmission = 3,
    L4_DispatchEligibility = 4,
    L5_Reconciliation = 5,
    L6_SimulatedEndToEnd = 6,
    Count = 7,
};

std::string_view to_string(EventType t);
std::string_view to_string(Lane l);
std::string_view to_string(ExecType t);
std::string_view to_string(AdmissionOutcome o);
std::string_view to_string(ServiceMode m);
std::string_view to_string(CommitOutcome o);
std::string_view to_string(Span s);
std::string_view to_string(Side s);

// --- the ring slot ---------------------------------------------------------

// What a producer hands to the engine. Trivially copyable by construction, so
// static_assert below is the contract doc 8 relies on, not a nicety.
struct InputEnvelope {
    EventId event_id{};
    std::uint64_t domain_seq = 0;    // assigned by the sequencer at admission
    std::uint64_t order_seq = 0;     // per-order causal position (LI-13)
    DomainId risk_domain = 0;
    std::uint32_t owner_epoch = 0;   // fencing token (LI-14)
    std::uint32_t tenant = 0;
    EventType type = EventType::None;
    Lane lane = Lane::NewOrder;
    Side side = Side::None;
    ExecType exec_type = ExecType::None;
    SymbolId symbol = 0;
    OrderId order_id = 0;
    OrderId orig_order_id = 0;       // the order a cancel/replace refers to
    ExecId exec_id = 0;
    Qty qty = 0;
    Px px = 0;
    Qty last_qty = 0;
    Px last_px = 0;
    std::uint64_t payload_hash = 0;
    // True when P01 has already accepted this as business evidence. Such an
    // event may not be dropped: if there is no capacity the engine degrades
    // instead (LI-20).
    bool accepted_evidence = false;
    bool poss_dup = false;           // FIX session replay marker (doc 19.3)
    std::uint64_t admission_ns = 0;  // L1 start, stamped before publish
    std::uint64_t receive_ns = 0;    // L0 start, stamped by the ingress adapter
    PoolHandle payload{};            // large payload, if any
};

static_assert(std::is_trivially_copyable_v<InputEnvelope>,
              "ring slots must be trivially copyable (design doc 8)");

// --- staged work and durable intent ---------------------------------------

// What the owner computed but has not made authoritative. Doc 13: staged state
// is not state. Nothing outside the engine may observe an effect derived from
// this until the store says Committed.
struct StagedEffect {
    bool order_changed = false;
    bool fill_appended = false;
    bool risk_changed = false;
    bool outbox_appended = false;
    bool quarantine = false;
};

// The atomic unit P06 commits. Doc 13 lists its parts: inbox dedup, journal
// event, order projection, fill ledger, risk reservation, command intent and
// outbox. All or nothing (LI-15).
struct DurableBusinessIntent {
    EventId event_id{};
    std::uint64_t domain_seq = 0;
    DomainId risk_domain = 0;
    std::uint32_t owner_epoch = 0;
    OrderId order_id = 0;
    EventType source_type = EventType::None;

    // Idempotency key for resolving a COMMIT_UNKNOWN. Doc 13: the resolution is
    // a query by this key, never a fresh business command (LI-17, CW-17).
    std::uint64_t idempotency_key = 0;

    bool write_inbox = false;
    bool write_journal = true;
    bool write_projection = false;
    bool write_fill = false;
    bool write_risk = false;
    bool write_outbox = false;

    // Projection after the reducer ran, carried so the store writes a value
    // rather than recomputing one.
    OrderId projection_order = 0;
    std::uint8_t projection_status = 0;
    Qty projection_cum_qty = 0;
    Qty projection_leaves_qty = 0;
    Px projection_avg_px = 0;

    ExecId fill_exec_id = 0;
    Qty fill_last_qty = 0;
    Px fill_last_px = 0;

    DomainId risk_domain_key = 0;
    Qty risk_reserved_delta = 0;
    Qty risk_position_delta = 0;

    // The original FIX command the dispatcher may send once, and only after
    // this transaction commits (LI-16).
    std::uint8_t outbox_kind = 0;  // 0 none, 1 New(35=D), 2 Cancel(F), 3 Replace(G)
    OrderId outbox_cl_ord_id = 0;
    OrderId outbox_orig_cl_ord_id = 0;
    SymbolId outbox_symbol = 0;
    Side outbox_side = Side::None;
    Qty outbox_qty = 0;
    Px outbox_px = 0;
};

// What the store hands back. Doc 19.5: a receipt from a previous epoch is
// stale and must not be applied, and a receipt that arrives out of domain_seq
// order must not release dispatch eligibility ahead of its predecessor.
struct CommitReceipt {
    EventId event_id{};
    std::uint64_t domain_seq = 0;
    DomainId risk_domain = 0;
    std::uint32_t owner_epoch = 0;
    CommitOutcome outcome = CommitOutcome::Committed;
    std::uint64_t journal_version = 0;
    std::uint64_t outbox_id = 0;
    std::uint64_t idempotency_key = 0;
    std::uint64_t commit_begin_ns = 0;
    std::uint64_t commit_end_ns = 0;
};

// One latency observation. Doc 14 requires the span, the outcome and the clock
// identity to travel with the number, so a histogram can never be built from
// samples whose denominator is unknown.
struct SpanSample {
    Span span = Span::L0_ReceiveToRoute;
    std::uint64_t ns = 0;
    std::uint64_t event_lo = 0;   // low half of event_id, for correlation
    std::uint32_t cpu = 0;
    std::uint8_t outcome = 0;     // AdmissionOutcome or CommitOutcome, per span
    bool valid = true;            // false when the duration check rejected it
};
static_assert(std::is_trivially_copyable_v<SpanSample>);

}  // namespace llx
